/**
 * Asset inventory for dist/manifest.json.
 *
 * Python consumers (and anyone verifying a published tarball) need to resolve
 * the shipped binaries — fonts, baked plates, the print stylesheet, the
 * Homebrewery theme — without guessing at paths. Every entry carries the
 * package-relative path, byte size and sha256, so a consumer can both locate
 * and verify what it loaded.
 *
 * Deterministic: directories are walked in sorted order and nothing records a
 * timestamp.
 */
import { createHash } from 'node:crypto';
import { readFileSync, readdirSync, statSync } from 'node:fs';
import { join, posix } from 'node:path';

/** Directory -> role, in manifest order. Only these ship as assets. */
const ROOTS = [
  { dir: 'fonts', role: 'font' },
  { dir: 'plate', role: 'plate' },
  { dir: 'print', role: 'print-css' },
  { dir: 'homebrewery', role: 'homebrewery-theme' },
];

const EXT_KIND = {
  '.ttf': 'font/ttf',
  '.woff2': 'font/woff2',
  '.png': 'image/png',
  '.css': 'text/css',
  '.less': 'text/less',
  '.js': 'text/javascript',
  '.json': 'application/json',
  '.py': 'text/x-python',
  '.txt': 'text/plain',
};

const walk = (dir) => {
  const out = [];
  for (const entry of readdirSync(dir, { withFileTypes: true }).sort((a, b) => (a.name < b.name ? -1 : 1))) {
    const path = join(dir, entry.name);
    if (entry.isDirectory()) out.push(...walk(path));
    else if (entry.isFile()) out.push(path);
  }
  return out;
};

const kindOf = (path) => {
  const dot = path.lastIndexOf('.');
  return EXT_KIND[path.slice(dot).toLowerCase()] ?? 'application/octet-stream';
};

export function buildManifest({ name, version }) {
  const assets = [];
  for (const { dir, role } of ROOTS) {
    let files;
    try {
      files = walk(dir);
    } catch {
      continue; // root absent in a partial checkout; nothing to inventory
    }
    for (const file of files) {
      const bytes = readFileSync(file);
      assets.push({
        path: file.split(/[\\/]/).join(posix.sep),
        role,
        type: kindOf(file),
        bytes: statSync(file).size,
        sha256: createHash('sha256').update(bytes).digest('hex'),
      });
    }
  }

  return {
    name,
    version,
    note: 'Generated by scripts/build-manifest.mjs. Paths are relative to the package root.',
    tokens: {
      css: 'dist/tokens.css',
      printCss: 'dist/tokens.print.css',
      less: 'dist/tokens.less',
      js: 'dist/tokens.js',
      json: 'dist/tokens.json',
    },
    assets,
  };
}
